// Bundles the game into one HTML page (three.js loads from the CDN as a UMD global).
//   node build.mjs                 -> dist/index.html with every level in src/levels/index.js
//   node build.mjs --level src/levels/golconda.js  -> dist/test-<id>.html with just that level
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const B = path.join(here, 'build');
fs.mkdirSync(B, { recursive: true });
const argv = process.argv.slice(2);
const li = argv.indexOf('--level');
const levelFile = li >= 0 ? path.resolve(argv[li + 1]) : null;

// Standalone map embeds the project and study catalogues; no server is required.
if (argv.includes('--fort-map')) {
  const output = await esbuild.build({entryPoints:[path.join(here,'src/fort-map.js')],bundle:true,format:'iife',minify:true,write:false,target:['es2020'],loader:{'.json':'json'}});
  const js=output.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
  const page=`<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Forts of the Subcontinent</title></head><body><script>${js}</script></body></html>`;
  const dir=path.join(here,'dist');fs.mkdirSync(dir,{recursive:true});
  const file=path.join(dir,'fort-map.html');fs.writeFileSync(file,page);
  console.log(path.relative(here,file),(page.length/1024).toFixed(0),'KB');process.exit(0);
}


// compact catalogue for the in-game Sources panel
const { default: lite } = await import('./src/data/source-catalogue.js');
fs.writeFileSync(path.join(B, 'catalog-lite.json'), JSON.stringify(lite));
fs.copyFileSync(path.join(here, 'src/data/land.json'), path.join(B, 'land.json'));
// lazy auto-T1 traces: the index is bundled, each trace becomes dist/traces/<id>.trace.js loaded on demand
{
  const TR = path.join(here, 'data/traces'), idx = path.join(TR, 'index.json');
  fs.writeFileSync(path.join(B, 'trace-index.json'), fs.existsSync(idx) ? fs.readFileSync(idx) : '{"sites":[]}');
  const out = path.join(here, 'dist/traces'); fs.mkdirSync(out, { recursive: true });
  if (fs.existsSync(TR)) for (const f of fs.readdirSync(TR).filter((f) => f.endsWith('.trace.json'))) fs.writeFileSync(path.join(out, f.replace(/\.json$/, '.js')), `window.__IN_RTS_TRACE(${fs.readFileSync(path.join(TR, f), 'utf8').replace(/<\/script/gi, '<\\/script')});\n`);
}

let entry = path.join(here, 'src/main.js');
let levels;
if (levelFile) {
  const mod = await import(pathToFileURL(levelFile).href + '?t=' + Date.now());
  levels = [mod.default];
  entry = path.join(B, `test-entry-${mod.default.id}.js`);
  const rel = (p) => JSON.stringify(path.relative(B, p).split(path.sep).join('/').replace(/^(?!\.)/, './'));
  fs.writeFileSync(entry, `import { bootWith } from ${rel(path.join(here, 'src/boot.js'))};\nimport L from ${rel(levelFile)};\nbootWith([L], { lazy: false });\n`);
} else {
  levels = (await import(pathToFileURL(path.join(here, 'src/levels/index.js')).href + '?t=' + Date.now())).LEVELS;
}

// Animal and character models in assets/fauna and assets/characters, embedded as base64 so the page stays one file.
// forts.world ships none (see LICENSES.md): only add models whose licence allows it, and record them there.
{
  const dir = path.join(here, 'assets/fauna'), out = path.join(here, 'src/game/fauna-data.js'), cdir = path.join(here, 'assets/characters');
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /\.(glb|jpg)$/.test(f)).sort() : [];
  const cfiles = fs.existsSync(cdir) ? fs.readdirSync(cdir).filter((f) => /\.glb$/.test(f)).sort() : [];
  const body = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(fs.readFileSync(path.join(dir, f)).toString('base64'))},`).concat(cfiles.map((f) => `  ${JSON.stringify('char:' + f)}: ${JSON.stringify(fs.readFileSync(path.join(cdir, f)).toString('base64'))},`)).join('\n');
  fs.writeFileSync(out, `// generated by build.mjs from assets/fauna; do not edit\nexport const FAUNA_FILES = {\n${body}\n};\n`);
}
const threeGlobal = {
  name: 'three-global',
  setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: 'three', namespace: 'three-global' }));
    b.onLoad({ filter: /.*/, namespace: 'three-global' }, () => ({ contents: 'module.exports = globalThis.THREE', loader: 'js' }));
  },
};
const out = await esbuild.build({
  entryPoints: [entry], bundle: true, format: 'iife', minify: argv.includes('--min'),
  plugins: [threeGlobal], write: false, target: ['es2020'], loader: { '.json': 'json' }, legalComments: 'none',
});
const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
let page = fs.readFileSync(path.join(here, 'src/page.html'), 'utf8');
const native = [...new Set(levels.map((l) => l.native?.text || '').join(''))].join('');
page = page.replace('__NATIVE_TEXT__', encodeURIComponent(native || 'अ'));
page = page.replace('<!--__SCRIPT__-->', () => `<script>${js}</script>`);
// inline three.js so the page works offline and needs no CDN
const threeSrc = fs.readFileSync(path.join(here, 'node_modules/three/build/three.min.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
page = page.replace('<script src="https://cdn.jsdelivr.net/npm/three@0.159.0/build/three.min.js"></script>', () => `<script>${threeSrc}</script>`);
page += '<style>' + fs.readFileSync(path.join(here, 'src/launcher/launcher.css'), 'utf8') + '</style>';
page += '<script>' + fs.readFileSync(path.join(here, 'src/launcher/launcher.js'), 'utf8').replace(/<\/script/gi, '<\\/script') + '</script>';
const dist = path.join(here, 'dist');
fs.mkdirSync(dist, { recursive: true });
const file = levelFile ? path.join(dist, `test-${levels[0].id}.html`) : path.join(dist, 'index.html');
fs.writeFileSync(file, page);
console.log(path.relative(here, file), (page.length / 1024).toFixed(0), 'KB');
