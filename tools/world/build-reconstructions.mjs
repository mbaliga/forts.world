// The ten constructed reconstructions of the first "Ten Forts of India" build, as one walkable page for the Forts of the World artifact.
//   node tools/world/build-reconstructions.mjs [out.html]      (default dist/reconstructions.html)
// The levels are the hand-built ones (each fort at three or four moments; heights, roofs and colours reconstructed and
// labelled as such in each era note). Later fort-fidelity work replaced some of them in the game with traced levels; the
// originals were kept as <id>-hand and are used here unchanged, apart from their display names.
// This repository ships neither the 0 A.D. animal and character models (CC BY-SA 3.0) nor the Janjira ground colours
// resampled from a drone photograph whose licence is not recorded, so animals and people use the built-in figures.
// Open a fort directly with ?fort=<level id>.
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');   // the repository root
const argv = process.argv.slice(2), li = argv.indexOf('--levels');
// --levels file[:Name],file[:Name]  builds a page from other level files in src/levels (default: the ten constructed reconstructions)
const custom = li >= 0 ? argv.splice(li, 2)[1].split(',').map((x) => { const [f, ...n] = x.split(':'); return [f, n.join(':') || f]; }) : null;
const out = path.resolve(argv[0] || path.join(here, 'dist/reconstructions.html'));
const B = path.join(here, 'build'); fs.mkdirSync(B, { recursive: true });

// the order of the original page
const TEN = [
  ['janjira-hand', 'Murud-Janjira'], ['sindhudurg-hand', 'Sindhudurg'], ['daulatabad-hand', 'Daulatabad'], ['golconda', 'Golconda'],
  ['gingee', 'Gingee'], ['gwalior-hand', 'Gwalior'], ['chittorgarh-hand', 'Chittorgarh'], ['kumbhalgarh', 'Kumbhalgarh'],
  ['mehrangarh', 'Mehrangarh'], ['jaisalmer-hand', 'Jaisalmer'],
];
export const RECONSTRUCTIONS = custom || TEN;

// what boot.js imports from build/: the Sources catalogue, the land outline, and an empty trace index (nothing lazy here)
const { default: lite } = await import(pathToFileURL(path.join(here, 'src/data/source-catalogue.js')).href);
fs.writeFileSync(path.join(B, 'catalog-lite.json'), JSON.stringify(lite));
fs.copyFileSync(path.join(here, 'src/data/land.json'), path.join(B, 'land.json'));
fs.writeFileSync(path.join(B, 'trace-index.json'), '{"sites":[]}');   // always the empty index: nothing is lazy here, and a full build leaves a 30 MB one behind

const rel = (p) => JSON.stringify(path.relative(B, p).split(path.sep).join('/').replace(/^(?!\.)/, './'));
const entry = path.join(B, 'reconstructions-entry.js');
fs.writeFileSync(entry, [
  `import { bootWith } from ${rel(path.join(here, 'src/boot.js'))};`,
  ...RECONSTRUCTIONS.map(([f], i) => `import L${i} from ${rel(path.join(here, 'src/levels', f + '.js'))};`),
  `const NAMES = ${JSON.stringify(RECONSTRUCTIONS.map(([, n]) => n))};`,
  `bootWith([${RECONSTRUCTIONS.map((_, i) => `L${i}`).join(', ')}].map((L, i) => ({ ...L, name: NAMES[i] })), { lazy: false });`,
].join('\n') + '\n');

const plugins = [
  { name: 'three-global', setup(b) {
    b.onResolve({ filter: /^three$/ }, () => ({ path: 'three', namespace: 'three-global' }));
    b.onLoad({ filter: /.*/, namespace: 'three-global' }, () => ({ contents: 'module.exports = globalThis.THREE', loader: 'js' }));
  } },
  { name: 'lighter-page', setup(b) {
    // The strategic map, campaign and atlas are not part of this page (their buttons are hidden below), so the research
    // workbook behind the map is left out to keep the page small. Everything else in this repository is already licence-clean
    // (the 0 A.D. models, GPL borders, HydroRIVERS and the Janjira photo tint stayed in IN-RTS; see LICENSES.md).
    b.onLoad({ filter: /data[\\/]smith-newton-2024\.json$/ }, () => ({ contents: '{"records":[]}', loader: 'json' }));
  } },
];
// fauna-data.js is generated by build.mjs and gitignored; esbuild still needs a file to resolve (forts.world ships no models)
const fd = path.join(here, 'src/game/fauna-data.js'); if (!fs.existsSync(fd)) fs.writeFileSync(fd, 'export const FAUNA_FILES = {};\n');

const r = await esbuild.build({ entryPoints: [entry], bundle: true, format: 'iife', minify: true, plugins, write: false, target: ['es2020'], loader: { '.json': 'json' }, legalComments: 'none' });
const js = r.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');
const levels = await Promise.all(RECONSTRUCTIONS.map(async ([f]) => (await import(pathToFileURL(path.join(here, 'src/levels', f + '.js')).href)).default));
const native = [...new Set(levels.map((l) => l.native?.text || '').join(''))].join('');
let page = fs.readFileSync(path.join(here, 'src/page.html'), 'utf8');
page = page.replace(/<title>[^<]*<\/title>/, '<title>Ten Forts of India</title>');
page = page.replace('__NATIVE_TEXT__', encodeURIComponent(native || 'अ'));
page = page.replace('<!--__SCRIPT__-->', () => `<style>[data-atlas],[data-camp],[data-map]{display:none!important}</style><script>${js}</script>`);
const threeSrc = fs.readFileSync(path.join(here, 'node_modules/three/build/three.min.js'), 'utf8').replace(/<\/script/gi, '<\\/script');
page = page.replace('<script src="https://cdn.jsdelivr.net/npm/three@0.159.0/build/three.min.js"></script>', () => `<script>${threeSrc}</script>`);
if (!/^<!doctype html>/i.test(page)) page = '<!doctype html>\n<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n' + page;
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, page);
console.log(path.relative(process.cwd(), out), (page.length / 1024).toFixed(0), 'KB;', RECONSTRUCTIONS.length, 'forts:', levels.map((l) => l.id).join(' '));
