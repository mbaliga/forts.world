import {test} from 'node:test';
import assert from 'node:assert/strict';
import {amer,jaigarh} from '../src/levels/amber-jaigarh.js';
import {buildingExistsInEra} from '../src/levels/gen.js';
import {fortEraAt} from '../src/game/campaign-battle.js';
import sources from '../src/data/source-catalogue.js';
test('Amer and Jaigarh prototypes retain dated sources and connection limits',()=>{
 for(const level of [amer,jaigarh]){
  assert.equal(fortEraAt(level,Number(level.eras[0].id)-1),null);
  assert.ok(level.eras.every(e=>e.sources.length&&e.conjecture));
  assert.ok(level.pois.every(p=>p.source));
 }
 assert.match(amer.pois.find(p=>p.id==='connection').text,/not visible/);
 assert.equal(amer.siteBoundary.length,20);
 assert.deepEqual(amer.coords,[26+59/60+5/3600,75+51/60+7/3600],'map marker uses UNESCO nomination site coordinate');
 assert.ok(amer.eras.every(e=>e.sources.includes('AME-18')));
 assert.ok(amer.eras.slice(1).every(e=>e.sources.includes('AME-19')));
 assert.ok(sources.some(s=>s.id==='AME-18'&&s.page_url==='https://whc.unesco.org/uploads/nominations/247rev.pdf'));
 assert.ok(sources.some(s=>s.id==='AME-19'&&s.page_url==='https://ignca.gov.in/asi_reports/RJJPR_659.pdf'));
 assert.deepEqual(amer.eras.map(e=>e.id),['1615','1640','1670','today']);
 const laterCourt={since:1667};
 assert.equal(buildingExistsInEra(laterCourt,'1610'),false,'1622–1667 court is absent from the c.1610 state');
 assert.equal(buildingExistsInEra(laterCourt,'1640'),false,'later court is withheld until after its uncertain construction interval');
 assert.equal(buildingExistsInEra(laterCourt,'1670'),true,'later court appears after the documented interval');
 assert.equal(buildingExistsInEra(laterCourt,'today'),true,'present-day scene retains later fabric');
 assert.equal(buildingExistsInEra(laterCourt,'hist'),true,'undated historic overview can still show all known phases');
 const halls=[];
 amer.build(new Proxy({era:'1615',ground:()=>0,pavilion:o=>halls.push(o)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.equal(halls.length,0,'the Diwan-i-Aam is withheld before its ASI-documented construction interval');
 amer.build(new Proxy({era:'1640',ground:()=>0,pavilion:o=>halls.push(o)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.equal(halls.length,0,'the hall is withheld during its uncertain construction interval');
 amer.build(new Proxy({era:'1670',ground:()=>0,pavilion:o=>halls.push(o)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.equal(halls.length,1,'the hall appears after the documented 1621–1667 interval');
 assert.deepEqual([halls[0].x,halls[0].y],amer.pois.find(p=>p.id==='diwan-aam-coordinate').at,'the hall uses its UNESCO coordinate');
 assert.deepEqual(halls[0].cols,[8,2],'the schematic hall uses two colonnade rows');
 assert.equal(halls[0].rot,0,'the hall follows the documented east-west axis');
 assert.equal(amer.siteBoundaryLabel,'Government of India forest-land application boundary (2022); not the fort wall line');
 assert.ok(amer.eras.every(e=>e.sources.includes('AME-08')));
 assert.ok(amer.eras.at(-1).sources.includes('AME-11'));
 assert.ok(amer.pois.some(p=>p.id==='stepwell'&&/eight-level stairs and octagonal kiosks/.test(p.text)));
 assert.ok(sources.some(s=>s.id==='AME-08'&&s.page_url.includes('411271221218474F0DigitalMap')));
 const zones=[];
 const world=new Proxy({era:'today',ground:()=>0,zone:(poly,name)=>zones.push({poly,name})},{get:(target,key)=>key in target?target[key]:(()=>{})});
 amer.build(world);
 const kundTanks=[],kundBuildings=[];
 amer.build(new Proxy({era:'today',ground:()=>0,tank:o=>kundTanks.push(o),building:o=>kundBuildings.push(o)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 const kundPoint=amer.pois.find(p=>p.id==='stepwell').at;
 const kund=kundTanks.find(t=>t.poly?.length===5&&Math.hypot(t.poly.reduce((sum,p)=>sum+p[0],0)/5-kundPoint[0],t.poly.reduce((sum,p)=>sum+p[1],0)/5-kundPoint[1])<0.01);
 assert.ok(kund,'Panna Meena ka Kund is separately rendered');
 assert.equal(kund.tiers,8,'the government heritage-walk description is represented in the stepwell geometry');
 assert.equal(kundBuildings.filter(b=>b.name?.startsWith('Panna Meena ka Kund corner kiosk')).length,4,'four current-view corner kiosks are represented');
 const boundaryZone=zones.find(z=>z.name===amer.siteBoundaryLabel);
 assert.equal(boundaryZone.poly.length,20,'the mapped applied-land polygon remains distinct from the fort wall');
 assert.ok(zones.some(z=>z.name.includes('existing-structure envelope')),'present satellite structure outline is represented separately');
 assert.ok(zones.some(z=>z.name.startsWith('Jaleb Chowk · mapped')&&z.poly.length===16));
 assert.ok(zones.some(z=>z.name.startsWith('Old Amer house · mapped footprint')));
 assert.ok(kundBuildings.some(b=>b.name?.startsWith('Old Amer house · mapped footprint')));
 assert.ok(amer.eras.at(-1).sources.includes('AME-21'));
 const earlyZones=[];
 amer.build(new Proxy({era:'1610',ground:()=>0,zone:(poly,name)=>earlyZones.push(name)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.ok(!earlyZones.includes(amer.siteBoundaryLabel),'present administrative boundary is absent from the 1610 scene');
 const historicalWater=[];amer.build(new Proxy({era:'1615',ground:()=>0,water:o=>historicalWater.push(o)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.equal(historicalWater.length,0,'modern mapped Maota shoreline is not projected into the past');
 const maota=amer.terrain('today').find(o=>o.op==='dig'&&o.poly?.length>20);assert.ok(maota,'present Maota uses a mapped outline');
 assert.ok(amer.eras.at(-1).sources.includes('AME-20'));
 assert.ok(jaigarh.eras.every(e=>e.sources.includes('JAI-G-04')));
 assert.deepEqual(jaigarh.eras.map(e=>e.id),['today']);
 assert.equal(fortEraAt(jaigarh,1740),null,'present mapped walls do not establish the 1740 layout');
 assert.match(jaigarh.eras[0].conjecture,/not a wall survey/);
 assert.deepEqual(jaigarh.spawnInside,[0,0],'exploration starts inside while gate and hill approach geometry remains unverified');
 assert.ok(jaigarh.eras.at(-1).sources.includes('JAI-G-05'));
 assert.ok(jaigarh.eras.every(e=>e.sources.includes('JAI-G-06')));
 assert.match(jaigarh.pois.find(p=>p.id==='water').text,/three large courtyard tanks supplied by pucca canals/);
 assert.ok(jaigarh.eras.at(-1).sources.includes('JAI-G-11'));
 assert.ok(jaigarh.eras.at(-1).sources.includes('JAI-G-12'));
 const jZones=[];
 jaigarh.build(new Proxy({era:'today',ground:()=>0,zone:(poly,name)=>jZones.push(name)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.ok(jZones.some(name=>name.includes('existing-structure envelope')),'Jaigarh present-day satellite outline is distinct from the larger fort extent');
 const tanks=[],covers=[];
 jaigarh.build(new Proxy({era:'today',ground:()=>0,tank:o=>tanks.push(o),building:o=>covers.push(o.name)},{get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.equal(tanks.filter(t=>t.name?.startsWith('Jaigarh courtyard reservoir')).length,3,'the three ASI-documented courtyard tanks are represented');
 assert.equal(covers.filter(name=>name?.startsWith('Jaigarh covered reservoir')).length,2,'the current water-system record distinguishes two covered reservoirs');
 const walls=[];
 const jWorld=new Proxy({era:'today',ground:()=>0,wall:o=>{walls.push(o);return {};},zone:()=>{}},{get:(target,key)=>key in target?target[key]:(()=>{})});
 jaigarh.build(jWorld);
 assert.ok(walls.filter(w=>w.closed===false&&w.path.length>=2).length>=18,'separate mapped wall segments are preserved');
 assert.ok(!walls.some(w=>w.closed===true),'the generated elliptical perimeter is removed');
 const grid=jaigarh.terrain('today').find(op=>op.op==='grid').grid;
 assert.deepEqual([grid.nx,grid.ny],[11,11]);
 assert.ok(jaigarh.eras[0].sources.includes('JAI-G-13')&&jaigarh.eras[0].sources.includes('JAI-G-14'));
});
