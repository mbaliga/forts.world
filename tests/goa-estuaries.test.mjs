import {test} from 'node:test';import assert from 'node:assert/strict';
import {reisMagos,chapora} from '../src/levels/goa-estuaries.js';
import {NODES_C, ROUTES_C} from '../src/data/south.js';
import {ownerAt} from '../src/data/konkan.js';
import {fortEraAt} from '../src/game/campaign-battle.js';
test('Goa campaign phases and local scenes respect the sourced dates',()=>{
 const c=NODES_C.find(n=>n.id==='chapora'),r=NODES_C.find(n=>n.id==='reis-magos');
 assert.equal(c.playable,'chapora');assert.equal(r.playable,'reis-magos');
 for(const [year,owner] of [[1683,'portuguese'],[1684,'maratha'],[1717,'portuguese'],[1739,'maratha'],[1741,'portuguese']]) assert.equal(ownerAt(c,year)?.owner,owner);
 assert.equal(r.phases[0].to,1707);assert.equal(r.phases[1].ev,'inferred');
 assert.equal(fortEraAt(chapora,1729),null);assert.equal(fortEraAt(reisMagos,1709),null);
 assert.equal(fortEraAt(chapora,1730),null,'the present mapped ruins do not establish the 1730 building state');
 assert.equal(fortEraAt(reisMagos,1710),null,'the modern outline is not presented as a reconstruction of 1710');
 assert.deepEqual(reisMagos.coords,[15.4965,73.80913]);
 assert.ok(reisMagos.outline.length>20,'the mapped outline replaces the generic oval');
 const dem=reisMagos.terrain().find(op=>op.op==='grid').grid;
 assert.deepEqual([dem.nx,dem.ny,dem.stride],[11,12,40]);
 assert.equal(Buffer.from(dem.data,'base64').length,11*12*2);
 assert.ok(reisMagos.eras[0].sources.includes('REIS-12'));
 assert.deepEqual(reisMagos.eras.map(e=>e.id),['today']);
 assert.equal(ROUTES_C.find(r=>r[0]==='aguada'&&r[1]==='reis-magos')?.[2],'road','same-bank connection must not be presented as a ferry crossing');
 assert.deepEqual(chapora.eras.map(e=>e.id),['today']);
 assert.deepEqual(chapora.coords,[15.6059263,73.7360558]);
 assert.deepEqual(chapora.units,{planScale:1,vScale:1});
 const xs=chapora.wallPath.map(p=>p[0]),ys=chapora.wallPath.map(p=>p[1]);
 assert.ok(Math.max(...xs)-Math.min(...xs)>290&&Math.max(...xs)-Math.min(...xs)<300);
 assert.ok(Math.max(...ys)-Math.min(...ys)>195&&Math.max(...ys)-Math.min(...ys)<205);
 const gates=[],tunnels=[];
 chapora.build(new Proxy({era:'today',ground:()=>67,wall:()=>({}),gate:g=>gates.push(g),tunnel:t=>tunnels.push(t)}, {get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.equal(gates.length,3,'the published plan identifies land, sea and river gates');
 assert.ok(gates.find(g=>g.name.startsWith('Land gate')).at[0]>80);
 assert.ok(gates.find(g=>g.name.startsWith('Sea gate')).at[0]<0);
 assert.ok(gates.find(g=>g.name.startsWith('River gate')).at[1]>70);
 assert.equal(tunnels.length,0,'unlocated tunnel routes must not be fabricated');
 const demChapora=chapora.terrain('today').find(op=>op.op==='grid').grid;
 assert.deepEqual([demChapora.nx,demChapora.ny,demChapora.stride],[11,11,80]);
 assert.equal(Buffer.from(demChapora.data,'base64').length,11*11*2);
 const grounded=[];chapora.build(new Proxy({era:'today',ground:()=>42,wall:()=>({}),gate:g=>grounded.push(g)}, {get:(target,key)=>key in target?target[key]:(()=>{})}));
 assert.ok(grounded.every(g=>g.floor===42),'gate floors follow sampled local ground rather than the former fixed plateau');
 assert.ok(chapora.eras[0].sources.includes('CHA-06'));
 for(const level of [chapora,reisMagos])assert.ok(level.eras.every(e=>e.sources.length&&/\b(?:not|no|unregistered)\b/i.test(e.conjecture)));
});
